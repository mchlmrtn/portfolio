    function renderFilters(currentResults = portfolioData) {
      const sCont = document.getElementById('skillFilters'), tCont = document.getElementById('toolFilters');
      sCont.innerHTML = ''; tCont.innerHTML = '';
      const skillCounts = {}, toolCounts = {};
      currentResults.forEach(item => {
        item.skills.forEach(s => skillCounts[s] = (skillCounts[s] || 0) + 1);
        item.tools.forEach(t => toolCounts[t] = (toolCounts[t] || 0) + 1);
      });
      Object.keys(skillCounts).sort().forEach(s => {
        const chip = document.createElement('span');
        chip.className = `tag tag-skill ${activeSkills.has(s) ? 'active' : ''}`;
        chip.innerHTML = `${s} <span style="opacity:0.5; font-size:0.7rem; margin-left:4px;">(${skillCounts[s] || 0})</span>`;
        chip.onclick = () => toggleTag('skill', s);
        sCont.appendChild(chip);
      });
      Object.keys(toolCounts).sort().forEach(t => {
        const chip = document.createElement('span');
        chip.className = `tag tag-tool ${activeTools.has(t) ? 'active' : ''}`;
        chip.innerHTML = `${t} <span style="opacity:0.5; font-size:0.7rem; margin-left:4px;">(${toolCounts[t] || 0})</span>`;
        chip.onclick = () => toggleTag('tool', t);
        tCont.appendChild(chip);
      });
    }

