    function highlightText(text, query) {
      if (!query || !text) return text;
      const regex = new RegExp(`(${query.replace(/[-\/\\\\^$*+?.()|[\\]{}]/g, '\\\\$&')})`, 'gi');
      return text.replace(regex, '<mark class="search-highlight">$1</mark>');
    }

    function getSnippet(text, query) {
      if (!text) return '';
      const idx = text.toLowerCase().indexOf(query.toLowerCase());
      if (idx === -1) return '';
      const start = Math.max(0, idx - 60);
      const end = Math.min(text.length, idx + query.length + 60);
      let snippet = text.substring(start, end);
      if (start > 0) snippet = '...' + snippet;
      if (end < text.length) snippet = snippet + '...';
      return highlightText(snippet, query);
    }

    function createLinks(files, search) {
      if (!files || files.length === 0) return '-';
      return files.map(file => {
        if (!file.path) return `<span class="file-missing">${highlightText(file.name, search)}</span>`;
        let url = file.path;
        const size = fileSizes[file.path] || '';
        const sizeLabel = size ? ` (${size})` : '';
        
        if (!url.startsWith('http')) {
          url = './' + encodeURI(url);
          if (file.name.match(/\.(docx?|xlsx?|pptx?|xls)$/i)) {
            const abs = `https://mchlmrtn.github.io/portfolio/${file.path}`;
            url = `https://docs.google.com/gview?url=${encodeURIComponent(abs)}&embedded=true`;
          }
        }
        
        const isYouTube = url.includes('youtube.com') || url.includes('youtu.be');
        const isExcel = file.name.match(/\.(xlsx?|xlsm|xls)$/i);
        const isGitHub = url.includes('github.com');
        
        let className = 'file-link';
        if (isYouTube) className = 'youtube-link';
        else if (isExcel) className = 'excel-link';
        else if (isGitHub) className = 'github-link';
        
        return `<a href="${url}" class="${className}" target="_blank" onclick="gtag('event', 'file_click', {'file_name': '${file.name}'});">${highlightText(file.name, search)}<span class="file-size">${sizeLabel}</span></a>`;
      }).join(' ');
    }

